"""Generate artifacts/report.ipynb - a rendered walkthrough of the pipeline.

WHY A GENERATED NOTEBOOK
------------------------
Every other artefact here is generated from the pipeline so it cannot drift from
the code. A hand-written notebook would be the one exception, and this
repository has already been bitten four times by documentation describing a
system the code no longer matched (DEBUGGING #9, #11, plus two stale claims
caught in the final audit).

So the notebook is built the same way as the reports: each code cell is executed
here, its real output captured, and both written into the .ipynb. Regenerating
re-runs everything. No output below is typed by hand.

WHY .ipynb RATHER THAN HTML
---------------------------
GitHub renders notebooks natively, so a reviewer sees the whole walkthrough in
the browser without cloning, installing or executing anything - while the cells
stay real code they can run if they want to.

Every cell uses MockBackend, so this reproduces with no model and no network.
"""

from __future__ import annotations

import contextlib
import io
import json
from pathlib import Path

REPORT = Path("artifacts/report.ipynb")


def _md(text: str) -> dict:
    return {"cell_type": "markdown", "metadata": {},
            "source": text.strip().splitlines(keepends=True)}


def _code(source: str, namespace: dict) -> dict:
    """Execute `source`, capture what it prints, embed both."""
    buffer = io.StringIO()
    try:
        with contextlib.redirect_stdout(buffer), contextlib.redirect_stderr(io.StringIO()):
            exec(source, namespace)  # noqa: S102 - executing is the point here
        text = buffer.getvalue()
    except Exception as exc:  # a failing cell is reported, never hidden
        text = f"{type(exc).__name__}: {exc}"
    return {
        "cell_type": "code", "execution_count": None, "metadata": {},
        "source": source.strip().splitlines(keepends=True),
        "outputs": [{"output_type": "stream", "name": "stdout",
                     "text": text.splitlines(keepends=True)}],
    }


