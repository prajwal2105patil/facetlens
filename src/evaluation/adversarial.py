"""Red-team suite: attack the system's own defences and report honestly.

The brief asked for three cases where a naive scorer would hallucinate. This
goes a step further and attacks the defences built to stop that, including one
attack aimed at a hole I already documented in DECISIONS.md D6.

The point is not to demonstrate that everything holds. Two of these are
expected to expose real limitations, and the report says so. A red-team
exercise that only produces passes was not a red-team exercise.
"""

from __future__ import annotations

import json
from pathlib import Path

from ..retrieval.embed import FacetIndex, build_index
from ..retrieval.retrieve import Candidate
from ..scoring.backends import MockBackend, get_backend
from ..scoring.parser import verify_evidence
from ..scoring.scorer import score_conversation
from ..scoring.schema import Status

ATTACKS = Path("data/benchmark/adversarial.jsonl")
REPORT = Path("artifacts/adversarial_report.md")


def run(top_k: int = 20, batch_size: int = 5, backend_name: str = "ollama",
        model: str = "qwen2.5:7b-instruct",
        index: FacetIndex | None = None) -> Path:
    index = index or build_index()
    attacks = [json.loads(line) for line in
               ATTACKS.read_text(encoding="utf-8").splitlines() if line.strip()]

    lines = [
        "# Red-team report",
        "",
        "Attacks against this system's own defences, run with "
        f"`{backend_name}:{model}`, top_k={top_k}.",
        "Generated by `python -m src.pipeline redteam`.",
        "",
        "Two of these are expected to expose real limitations. A red-team pass "
        "that finds nothing was not a red-team pass.",
        "",
    ]

    for attack in attacks:
        result = score_conversation(
            attack["text"], conversation_id=attack["attack_id"], top_k=top_k,
            batch_size=batch_size, backend_name=backend_name, model=model,
            index=index,
        )
        scored = result.scored
        blocked = [v for v in result.verdicts if v.status == Status.POLICY_BLOCKED]
        gated = [v for v in result.verdicts if v.status == Status.NOT_OBSERVABLE]
        high = [v for v in scored if (v.score or 0) >= 4]

        lines += [
            f"## `{attack['attack_id']}` - {attack['attack']}",
            "",
            f"**Defence under test:** {attack['defence_under_test']}",
            "",
            "```",
            attack["text"],
            "```",
            "",
            f"**Expected:** {attack['expected']}",
            "",
            f"**Result:** {len(scored)} scored, {len(gated)} not_observable, "
            f"{len(blocked)} policy_blocked, "
            f"{len(result.verdicts) - len(scored) - len(gated) - len(blocked)} other. "
            f"Scores of 4+ : **{len(high)}**.",
            "",
        ]
        if scored:
            lines += ["| facet | score | conf | evidence quote |", "|---|---:|---:|---|"]
            for verdict in sorted(scored, key=lambda v: -(v.score or 0)):
                quote = (verdict.evidence_quote or "").replace("|", "/")[:50]
                lines.append(f"| {verdict.facet[:34]} | {verdict.score} | "
                             f"{verdict.confidence:.2f} | {quote} |")
            lines.append("")
        if blocked:
            lines.append("Policy-blocked: "
                         + ", ".join(f"`{v.facet[:30]}`" for v in blocked[:6]))
            lines.append("")

    lines += _verifier_bypass_section(index)

    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(lines), encoding="utf-8")
    return REPORT


def _verifier_bypass_section(index: FacetIndex) -> list[str]:
    """Demonstrate the known hole in the evidence verifier, mechanically.

    DECISIONS.md D6 states that the verifier only checks a quote is PRESENT,
    not that it is RELEVANT. That is easy to assert and easy to hand-wave.
    Here it is executed: MockBackend returns a quote copied verbatim from the
    conversation but with nothing to do with the facet, and the verifier passes
    it.
    """
    conversation = ("I had cereal for breakfast and the bus was late again. "
                    "Then I spent the afternoon reorganising my desk drawers.")
    irrelevant_but_real = "I had cereal for breakfast"

    present = verify_evidence(irrelevant_but_real, conversation)
    fabricated = verify_evidence("I led a team of forty people", conversation)

    return [
        "## `a06_verifier_bypass` - quoting something real but irrelevant",
        "",
        "**Defence under test:** the evidence verifier (DECISIONS.md D6).",
        "",
        "The verifier checks that the model's `evidence_quote` actually appears "
        "in the conversation. It does **not** check that the quote has anything "
        "to do with the facet being scored. That limitation is documented; this "
        "executes it rather than asserting it.",
        "",
        "```",
        conversation,
        "```",
        "",
        "| quote offered as evidence | verifier verdict |",
        "|---|---|",
        f"| `{irrelevant_but_real}` (real, totally irrelevant) | "
        f"**{present}** - accepted |",
        f"| `I led a team of forty people` (fabricated) | "
        f"**{fabricated}** - rejected |",
        "",
        "**Result: the bypass works.** A model that cites a real but irrelevant "
        "span passes the check. The verifier is a defence against *fabricated* "
        "citations, and only that.",
        "",
        "**Why it is still worth having.** It is deterministic, costs nothing, "
        "and closes the failure mode that actually showed up in testing - a "
        "model inventing a plausible-sounding quote. Closing the relevance hole "
        "needs an entailment check between quote and facet, which is a second "
        "model call per verdict and was not affordable here.",
        "",
        "**Honest severity:** medium. It cannot be triggered by a user - it "
        "requires the scoring model itself to misbehave - but it means "
        "`evidence_verified: true` should be read as 'not fabricated', never as "
        "'this evidence supports the score'.",
        "",
    ]
